#!/usr/bin/env python3
"""Extract every shell command and file write from claude_transcript.jsonl, verbatim.

  python3 tools/extract_commands.py   (run from the episode folder)

Writes tools/commands.md: one numbered entry per Bash call / Write / Edit, in transcript
order, with its description and the exact text sent. Nothing is reformatted; the transcript
itself is never modified. The numbers (#N) are what TOOLS.md refers to.
"""
import json, os

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(HERE, "claude_transcript.jsonl")
OUT = os.path.join(HERE, "tools", "commands.md")

status = {}  # tool_use_id -> "ok" / "error" (the user-side tool_result says which)
for line in open(SRC):
    d = json.loads(line)
    m = d.get("message")
    if isinstance(m, dict) and isinstance(m.get("content"), list):
        for b in m["content"]:
            if b.get("type") == "tool_result":
                txt = json.dumps(b.get("content"))
                status[b["tool_use_id"]] = ("denied" if "Permission for this action was denied" in txt
                                            else "error" if b.get("is_error") else "ok")

entries = []
seen = set()  # a tool call can appear on several transcript lines; keep the first
for line in open(SRC):
    d = json.loads(line)
    m = d.get("message")
    if not isinstance(m, dict) or not isinstance(m.get("content"), list):
        continue
    for b in m["content"]:
        if b.get("type") != "tool_use" or b.get("name") not in ("Bash", "Write", "Edit"):
            continue
        if b.get("id") in seen:
            continue
        seen.add(b.get("id"))
        i = b["input"]
        if b["name"] == "Bash":
            entries.append(("Bash", i.get("description", ""), i["command"], d.get("timestamp", ""), status.get(b["id"], "?")))
        elif b["name"] == "Write":
            entries.append(("Write", i["file_path"], i["content"], d.get("timestamp", ""), status.get(b["id"], "?")))
        else:
            entries.append(("Edit", i["file_path"], "--- old\n" + i["old_string"] + "\n+++ new\n" + i["new_string"], d.get("timestamp", ""), status.get(b["id"], "?")))

with open(OUT, "w") as f:
    f.write("# Every command and file write, verbatim (generated by extract_commands.py)\n\n")
    for n, (kind, desc, body, ts, st) in enumerate(entries, 1):
        fence = "````" if "```" in body else "```"
        f.write(f"## #{n} {kind}: {desc}\n\n{ts} · result: {st}\n\n{fence}{'bash' if kind == 'Bash' else ''}\n{body}\n{fence}\n\n")
print(f"{len(entries)} entries -> {OUT}")
